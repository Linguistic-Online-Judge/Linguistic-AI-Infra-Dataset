// Explicit school-development acceptance: two real UPOS jobs, not a benchmark.
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { randomUUID } from 'node:crypto';
import { startBrowser } from './cdp.mjs';

if (!process.argv.includes('--run-real-qwen')) throw new Error('Requires --run-real-qwen; creates two real model evaluations.');
const base = 'http://127.0.0.1:8090';
const directory = resolve(import.meta.dirname, '../../runtime/browser-tests', `qwen-pages-${Date.now()}`);
mkdirSync(directory, { recursive: true });
const report = { schema_version: 'qwen-pages-acceptance-v1', started_at: new Date().toISOString(), browser_verified: true, independent_benchmark: false, rows: [], checks: [], passed: false };
const save = () => writeFileSync(resolve(directory, 'report.json'), JSON.stringify(report, null, 2) + '\n', { mode: 0o600 });
const check = name => { report.checks.push(name); save(); console.log(`PASS ${name}`); };
const browser = await startBrowser(directory);
const nonce = randomUUID().slice(0, 12);
const email = `pages-${nonce}@example.test`;
const password = `Pages-${randomUUID()}`;
const writes = [];
const prompt = 'Assign exactly one Universal Dependencies UPOS tag to each input token. Preserve token order and token count. Use only ADJ, ADP, ADV, AUX, CCONJ, DET, INTJ, NOUN, NUM, PART, PRON, PROPN, PUNCT, SCONJ, SYM, VERB, X. Return only the required JSON object with the tags array. Do not include explanations or markdown.';
browser.on('Network.requestWillBeSent', event => {
  if (new URL(event.request.url).pathname === '/v1/submissions' && event.request.method === 'POST') writes.push(event.request.postData);
});
const readyResult = () => browser.wait("state.view === 'result' && !state.submitting && elements['result-content'].textContent.includes('评测已完成') && !!state.promptRecord", 'real result and owner prompt', 420000);
try {
  await browser.send('Network.enable');
  await browser.viewport(1440, 1000);
  await browser.navigate(base + '/');
  await browser.wait("state.authMode === 'cookie' && state.development?.evaluation_mode === 'qwen' && state.challenges.length >= 26", 'school app loaded', 45000);
  assert.equal(await browser.evaluate("document.querySelector('.wordmark-mark').naturalWidth > 0"), true);
  assert.equal(await browser.evaluate("getComputedStyle(document.querySelector('.nav-link.is-active')).color"), 'rgb(14, 65, 156)');
  assert.equal(await browser.evaluate("document.querySelector('a[href=\"/docs\"]').closest('details')?.id"), 'development-panel');
  assert.equal(await browser.evaluate("elements['development-panel'].open"), false);
  const languages = await browser.evaluate("Array.from(elements['language-filter'].options).map(option=>option.value).filter(Boolean)");
  assert.equal(languages.length, 18);
  for (const language of languages) {
    await browser.fill('#language-filter', language);
    assert.ok(await browser.evaluate("elements['challenge-list'].children.length > 0"));
    assert.equal(await browser.evaluate("elements['challenge-list'].firstElementChild.children[1].textContent"), language);
  }
  await browser.click('#filters-clear');
  report.catalog_count = await browser.evaluate('state.challenges.length');
  report.language_count = languages.length;
  const tasks = await browser.evaluate("state.challenges.filter(c=>c.task==='upos' && c.accepting_submissions).map(c=>({id:c.challenge_id,language:c.language,samples:c.sample_count,identity:c.evaluation_identity_sha256}))");
  assert.equal(tasks.length, 18);
  for (const width of [1440, 768, 390, 320]) {
    await browser.viewport(width, 900, width < 640);
    assert.ok(await browser.evaluate('document.documentElement.scrollWidth <= innerWidth + 1'));
    await browser.screenshot(`school-catalog-${width}`);
  }
  check('18 real catalog languages, 26 tasks, Fudan brand, collapsed developer documentation, four widths');
  await browser.viewport(1440, 1000);
  await browser.evaluate("openAuthDialog('register')");
  await browser.fill('#auth-email', email);
  await browser.click('#auth-submit');
  await browser.wait("!state.authBusy && !elements['auth-notice'].classList.contains('is-hidden')");
  await browser.click('#auth-close');
  await browser.click('#development-panel summary');
  await browser.click('#development-mail-refresh');
  await browser.wait(`!elements['development-mail-refresh'].disabled && elements['development-mail'].textContent.includes(${JSON.stringify(email)})`);
  await browser.evaluate(`Array.from(elements['development-mail'].querySelectorAll('li')).find(item=>item.textContent.includes(${JSON.stringify(email)})).querySelector('a').click()`);
  await browser.wait("state.authPage === 'verify-email'");
  await browser.fill('#auth-handle', `Pages-${nonce}`);
  await browser.fill('#auth-password', password);
  await browser.click('#auth-submit');
  await browser.wait("state.authPage === 'login' && !state.authBusy");
  await browser.fill('#auth-email', email);
  await browser.fill('#auth-password', password);
  await browser.click('#auth-submit');
  await browser.wait("!!state.user && !elements['auth-dialog'].open");
  report.test_user_id = await browser.evaluate('state.user.user_id');
  report.test_handle = await browser.evaluate('state.user.public_handle');
  // Keep development-only credentials private for recovery without resetting an account.
  writeFileSync(resolve(directory, 'test-account.json'), JSON.stringify({ email, password }), { mode: 0o600 });
  check('new ordinary account registered and logged in through actual school cookie service');
  for (const language of ['English', 'Chinese']) {
    const task = tasks.find(item => item.language === language);
    assert.equal(task.samples, 50);
    await browser.evaluate(`location.hash=${JSON.stringify('#challenge/' + task.id)}`);
    await browser.wait(`state.view === 'practice' && state.selectedChallengeId === ${JSON.stringify(task.id)} && teachingState.status === 'ready'`);
    await browser.click('#lesson-tab-example');
    assert.equal(await browser.evaluate("elements['lesson-example'].hidden"), false);
    await browser.click('#lesson-tab-scoring');
    assert.match(await browser.evaluate("elements['scoring-description'].textContent"), /词元准确率/);
    await browser.click('#lesson-tab-description');
    await browser.click('#template-zero');
    assert.ok(await browser.evaluate("elements['student-prompt'].value.length > 30"));
    await browser.fill('#student-prompt', prompt);
    await browser.screenshot(`school-practice-${language}`);
    const row = { language, challenge_id: task.id, evaluation_identity: task.identity, status: 'submitting' };
    report.rows.push(row); save();
    await browser.click('#run-button');
    await browser.wait(`state.activeSubmission?.challenge_id === ${JSON.stringify(task.id)} && !state.submitting`, 'real submission accepted', 45000);
    row.submission_id = await browser.evaluate('state.activeSubmission.submission_id');
    row.status = 'accepted'; save();
    await browser.wait("['succeeded','failed','rejected'].includes(state.activeSubmission?.status)", `${language} generation finished`, 420000);
    const result = await browser.evaluate("apiRequest('/v1/submissions/'+state.activeSubmission.submission_id+'/result',{},true)");
    row.status = result.outcome;
    row.samples_total = result.samples_total;
    row.samples_valid = result.samples_valid;
    row.score = result.score;
    row.errors = result.errors;
    save();
    assert.equal(result.outcome, 'succeeded');
    assert.equal(result.model_identity.model, 'Qwen/Qwen3.5-9B');
    assert.equal(result.model_identity.runtime, 'vllm');
    assert.equal(result.samples_total, 50);
    await readyResult();
    assert.equal(await browser.evaluate("elements['submitted-prompt'].textContent"), prompt);
    const hash = await browser.evaluate('location.hash');
    await browser.navigate(base + '/' + hash);
    await readyResult();
    assert.equal(await browser.evaluate("elements['submitted-prompt'].textContent"), prompt);
    await browser.click('#continue-editing');
    assert.equal(await browser.evaluate("elements['student-prompt'].value"), prompt);
    assert.equal(writes.length, report.rows.length, 'Reload and reuse send no extra submissions');
    await browser.evaluate(`location.hash=${JSON.stringify(hash)}`);
    await readyResult();
    await browser.click('#result-leaderboard');
    await browser.wait('!state.leaderboardLoading');
    assert.equal(await browser.evaluate('state.leaderboardIdentity'), task.identity);
    assert.ok(await browser.evaluate(`elements['leaderboard-list'].textContent.includes(${JSON.stringify(report.test_handle)})`));
    await browser.click('#leaderboard-back');
    await readyResult();
    await browser.screenshot(`school-result-${language}`);
    check(`${language}: 50 real samples, saved prompt, result reload, reuse, exact leaderboard`);
  }
  assert.equal(writes.length, 2);
  await browser.evaluate("location.hash='#runs'");
  await browser.wait("state.view==='runs' && !state.runsLoading && elements['runs-list'].children.length===2");
  await browser.screenshot('school-history');
  await browser.click('#runs-list button');
  await readyResult();
  await browser.viewport(390, 900, true);
  await browser.screenshot('school-result-390');
  await browser.click('#session-button');
  await browser.click('#auth-submit');
  await browser.wait("!state.user && !elements['auth-dialog'].open");
  assert.equal(await browser.evaluate("elements['submitted-prompt'].textContent"), '');
  await browser.evaluate("openAuthDialog('login')");
  await browser.fill('#auth-email', 'admin@example.test');
  await browser.fill('#auth-password', 'Local-only-passphrase-2026!');
  await browser.click('#auth-submit');
  await browser.wait("state.user?.role==='admin' && !elements['auth-dialog'].open");
  assert.equal(await browser.evaluate(`apiRequest('/v1/submissions/${report.rows[0].submission_id}/prompt',{},true).then(()=>200,error=>error.status)`), 404);
  await browser.evaluate("location.hash='#admin'");
  await browser.wait(`adminState.items.length===${report.catalog_count} && !adminState.busy`);
  await browser.viewport(1440, 1000);
  await browser.screenshot('school-admin-readonly');
  check('two-row owner history, logout cleanup, existing admin login/read, admin denied another owner prompt');
  await browser.click('#session-button');
  await browser.click('#auth-submit');
  await browser.wait('!state.user');
  assert.deepEqual(browser.exceptions, []);
  report.passed = true;
} catch (error) {
  report.failure = error.message;
  await browser.screenshot('failure').catch(() => {});
  process.exitCode = 1;
} finally {
  report.finished_at = new Date().toISOString();
  report.submission_post_count = writes.length;
  save();
  await browser.close();
}
console.log(`Report: ${resolve(directory, 'report.json')}`);
